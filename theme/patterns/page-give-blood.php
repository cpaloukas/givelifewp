<!-- wp:paragraph {"className":"givelifewp-lead","textColor":"muted","fontSize":"large"} -->
<p class="givelifewp-lead has-muted-color has-text-color has-large-font-size">Blood can't be made in a lab. Every bag in every hospital was given by a person who took an hour out of their day. Here's why it matters, and how you can be one of them.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"why"} -->
<h2 class="wp-block-heading" id="why">Why it matters</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Donated blood goes to people in surgery, to accident and trauma patients, to mothers who bleed heavily during childbirth, to people with cancer, and to people with conditions like sickle cell disease or thalassaemia who need transfusions for life.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>It doesn't keep for long. Red cells last up to about six weeks, and platelets only about a week. So supplies need topping up all the time, not just after a disaster makes the news. That's why regular donors matter most.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"className":"givelifewp-facts"} -->
<ul class="wp-block-list givelifewp-facts"><!-- wp:list-item -->
<li><strong>Up to 3</strong> people can be helped by one whole blood donation, once it's separated into red cells, plasma and platelets.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>About 1 hour</strong> for the whole visit. The donation itself takes around 10 minutes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>About 1 week</strong> is all platelets last, which is why they're always needed.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"anchor":"ways-to-give"} -->
<h2 class="wp-block-heading" id="ways-to-give">Ways to give</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3,"anchor":"whole-blood"} -->
<h3 class="wp-block-heading" id="whole-blood">Whole blood</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The classic donation: just under half a litre (about a pint), taken from a vein in your arm in around 10 minutes. It's where almost everyone starts. Depending on your country, you can usually give every 8 to 16 weeks.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"anchor":"platelets"} -->
<h3 class="wp-block-heading" id="platelets">Platelets</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Platelets help blood clot. They're vital for people having cancer treatment, organ transplants and major surgery. A machine collects only the platelets and returns the rest of your blood to you. It takes longer, often between one and a half and three hours, but you can usually give more often than whole blood. Many services invite experienced whole blood donors to switch.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"anchor":"plasma"} -->
<h3 class="wp-block-heading" id="plasma">Plasma</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Plasma is the straw-coloured liquid part of blood. It's used for burns, trauma and bleeding, and to make medicines for people with immune and clotting disorders. Like platelets, it's collected by a machine that returns your red cells, and it usually takes about an hour. Not every country collects plasma from volunteers, so check with your blood service.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"who-can-give"} -->
<h2 class="wp-block-heading" id="who-can-give">Who can give</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>More people than you might think. The exact rules belong to your local blood service, but in most places you can give if you:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>are in good health and feeling well on the day,</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>are an adult, usually from 17 or 18 (16 in some places, with consent), and</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>weigh at least 50 kg (about 110 lb).</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>Some things mean waiting a while before you give, such as a cold or infection, a recent tattoo or piercing, some medicines, recent travel to certain areas, pregnancy, or a recent birth. Most of these are temporary. Each blood service has an online check or a phone line, so a quick look before booking saves a wasted trip.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><a href="/find-a-donor-service/">Find your blood service and its eligibility check</a></p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"blood-type"} -->
<h2 class="wp-block-heading" id="blood-type">Know your blood type</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Don't know your blood type? Giving blood is one of the easiest ways to find out: most blood services will tell you after your first donation, often in their app or on a donor card.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Every type is needed. A few are special. <strong>O negative</strong> red cells can be given to almost anyone, so they're what emergency teams reach for before they know a patient's type. <strong>AB</strong> plasma can be given to anyone, which makes AB donors especially useful for plasma and platelets.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"free-check"} -->
<h2 class="wp-block-heading" id="free-check">A small health check along the way</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Before you give, staff usually check your iron (haemoglobin) with a finger-prick test, and sometimes your blood pressure and pulse. Afterwards, every donation is tested for infections such as HIV, hepatitis B, hepatitis C and syphilis. If a result needs attention, the blood service will contact you and help you get care.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Please don't give blood just to get tested. Tests can miss very recent infections, so a clinic or your doctor is the right place if you think you might have been exposed.</p>
<!-- /wp:paragraph -->

