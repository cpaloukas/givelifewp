<!-- wp:heading {"anchor":"why"} -->
<h2 class="wp-block-heading" id="why">Why it matters</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Donated blood goes to people in surgery, to accident and trauma patients, to mothers who bleed heavily during childbirth, to children and adults with cancer, and to people with conditions like sickle cell disease or thalassaemia who need transfusions for life.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>It doesn’t keep for long. Red cells last up to about six weeks, and platelets only about a week. So supplies need topping up all the time, not just after a disaster makes the news. That’s why regular donors matter most.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"ways-to-give"} -->
<h2 class="wp-block-heading" id="ways-to-give">Ways to give</h2>
<!-- /wp:heading -->

<!-- wp:group {"anchor":"whole-blood","className":"givelifewp-card givelifewp-way givelifewp-way--blood","layout":{"type":"default"}} -->
<div id="whole-blood" class="wp-block-group givelifewp-card givelifewp-way givelifewp-way--blood"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Whole blood</h3>
<!-- /wp:heading -->

<!-- wp:list {"className":"givelifewp-chips"} -->
<ul class="wp-block-list givelifewp-chips"><!-- wp:list-item -->
<li>About 10 min to give</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>About 1 hour in total</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Every 8–16 weeks</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>The classic donation: just under half a litre (about a pint), taken from a vein in your arm. It’s where almost everyone starts. Afterwards it’s separated into red cells, plasma and platelets, so one donation can help up to three people. How often you can give depends on your country, usually every 8 to 16 weeks.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"anchor":"platelets","className":"givelifewp-card givelifewp-way givelifewp-way--platelets","layout":{"type":"default"}} -->
<div id="platelets" class="wp-block-group givelifewp-card givelifewp-way givelifewp-way--platelets"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Platelets</h3>
<!-- /wp:heading -->

<!-- wp:list {"className":"givelifewp-chips"} -->
<ul class="wp-block-list givelifewp-chips"><!-- wp:list-item -->
<li>About 90 min to give</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>As often as every 1–2 weeks</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>Platelets help blood clot. They’re most often given to <strong>children and adults with leukaemia and other cancers</strong>, whose treatment stops their bodies making enough, and to people having bone marrow or organ transplants, heart surgery, or bleeding badly after an accident or childbirth.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A machine collects only the platelets and returns the rest of your blood to you. Your body replaces them within a few days, so you can usually give much more often than whole blood. Platelets last only about a week, which is why they’re always in short supply. Many services invite regular whole blood donors to switch.</p>
<!-- /wp:paragraph -->

