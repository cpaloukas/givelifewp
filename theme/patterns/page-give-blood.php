<div id="plasma" class="wp-block-group givelifewp-card givelifewp-way givelifewp-way--plasma"><!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Plasma</h3>
<!-- /wp:heading -->

<!-- wp:list {"className":"givelifewp-chips"} -->
<ul class="wp-block-list givelifewp-chips"><!-- wp:list-item -->
<li>About 45 min to give</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>As often as every 1–2 weeks</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>Plasma is the straw-coloured liquid part of blood. It’s used for burns, trauma and heavy bleeding, and to make medicines for people with immune and clotting disorders. A machine collects the plasma and returns your red cells. Not every country collects plasma from volunteers, so check with your blood service.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:heading {"anchor":"who-can-give"} -->
<h2 class="wp-block-heading" id="who-can-give">Who can give</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>More people than you might think. The exact rules belong to your local blood service, but in most places you can give if you:</p>
<!-- /wp:paragraph -->

<!-- wp:list {"className":"givelifewp-checks"} -->
<ul class="wp-block-list givelifewp-checks"><!-- wp:list-item -->
<li>are in good health and feeling well on the day,</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>are an adult, usually from 17 or 18 (16 in some places, with consent), and</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>weigh at least 50 kg (about 110 lb).</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>Some things mean waiting a while before you give, such as a cold or infection, a recent tattoo or piercing, some medicines, recent travel to certain areas, pregnancy, or a recent birth. Most of these are temporary. Every blood service has an online check or a phone line, so a quick look before booking saves a wasted trip.</p>
<!-- /wp:paragraph -->

