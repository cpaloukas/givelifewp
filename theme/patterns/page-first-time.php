<!-- wp:heading {"anchor":"on-the-day"} -->
<h2 class="wp-block-heading" id="on-the-day">What happens on the day</h2>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true,"className":"givelifewp-steps givelifewp-steps--cards"} -->
<ol class="wp-block-list givelifewp-steps givelifewp-steps--cards"><!-- wp:list-item -->
<li><strong>Arrive and register.</strong> Bring photo ID. Some services ask you to fill in a health questionnaire online beforehand.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>A short private chat.</strong> A staff member goes through your answers in private and checks your iron with a quick finger prick.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>The donation.</strong> You lie back in a comfortable chair. After a quick pinch, whole blood takes around 10 minutes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Rest and a snack.</strong> Stay for 10 to 15 minutes with a drink and something to eat before you head off.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

<!-- wp:paragraph {"className":"givelifewp-muted"} -->
<p class="givelifewp-muted">Allow about an hour in total for whole blood. Plasma (about 45 minutes in the chair) and platelets (about 90) take longer.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"questions"} -->
<h2 class="wp-block-heading" id="questions">Common questions</h2>
<!-- /wp:heading -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>Does it hurt?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>There’s a brief pinch when the needle goes in, a bit like a blood test. Most people feel little or nothing after that.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>What should I do before I go?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>Eat a proper meal in the few hours before, drink plenty of water, and get a good night’s sleep. Wear a top with sleeves that roll up easily. Don’t go on an empty stomach.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>What about afterwards?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>Keep drinking fluids, keep the plaster on for a few hours, and skip heavy exercise or lifting with that arm for the rest of the day. Your body replaces the fluid within a day or two and the red cells over the following weeks.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>What if I feel faint?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>Tell a staff member straight away, even if it’s mild. They’ll lower your chair, raise your legs and look after you. They may also give you a sugary drink or a glucose tablet that melts in your mouth for a quick lift. It’s not common, and it’s much less likely if you’ve eaten and had plenty to drink.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>I have a tattoo or piercing. Can I give?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>Usually yes, after a waiting period. That’s often a few months from when it was done, but it varies by country, so check with your blood service.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>I take medication. Can I give?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>Many medicines are fine, some mean waiting, and a few mean you can’t give. Check your blood service’s eligibility pages or call them. Never stop taking a medicine just so you can donate.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>How often can I give?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>For whole blood it’s usually every 8 to 16 weeks, depending on your country. Platelets and plasma can be given far more often, in some countries as often as every week, because your body replaces them within days. Your blood service will tell you when you’re next due.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"givelifewp-faq"} -->
<details class="wp-block-details givelifewp-faq"><summary>What if I’m turned away?</summary><!-- wp:paragraph {"placeholder":"Type / to add a hidden block"} -->
<p>It happens, often because of low iron or a recent illness, and it’s usually temporary. It’s not a failure: it’s the service looking after you. Ask when you can try again. It’s also why giving regularly matters so much. If you only go when someone close to you needs blood, that might be the day you’re turned away. Regular donors keep the shelves stocked for everyone, including the people you love.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:heading {"anchor":"myths"} -->
<h2 class="wp-block-heading" id="myths">Myths vs facts</h2>
<!-- /wp:heading -->

<!-- wp:list {"className":"givelifewp-myths"} -->
<ul class="wp-block-list givelifewp-myths"><!-- wp:list-item -->
<li><strong>Myth: you can catch something by giving blood.</strong> <span>Every needle and bag is sterile, used once and thrown away. Nothing that touches you has touched anyone else.</span></li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>Myth: my blood type is common, so it isn’t needed.</strong> <span>Common types are used the most, so they’re needed the most. Hospitals go through them fastest.</span></li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>Myth: giving blood leaves you weak for weeks.</strong> <span>Most people feel normal the same day. The fluid is replaced within a day or two, and your body quietly rebuilds the red cells over the following weeks.</span></li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>Myth: vegetarians and vegans can’t give.</strong> <span>Diet doesn’t stop you, as long as your iron level is fine on the day. Iron-rich foods like beans, lentils and leafy greens help.</span></li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>Myth: hospitals have plenty; they only need blood after disasters.</strong> <span>Blood is used every day and doesn’t keep for long: platelets last about a week. Steady, regular donors matter far more than one-off rushes.</span></li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>Myth: I’m too old to start.</strong> <span>Many services welcome new donors well into their sixties, and regular donors can often keep giving for longer. Check your local rules.</span></li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

